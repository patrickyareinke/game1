def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "..", "assets", "fonts")
    os.makedirs(out_dir, exist_ok=True)
    H = 9
    glyphs = sorted(G.items(), key=lambda kv: kv[0])
    cols = 16
    cw, ch = 7, 11
    rows_n = (len(glyphs) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cw, rows_n * ch), (0, 0, 0, 0))
    lines = []
    for i, (char, rows) in enumerate(glyphs):
        w = len(rows[0])
        x0, y0 = (i % cols) * cw, (i // cols) * ch
        for y, row in enumerate(rows):
            for x, px in enumerate(row):
                if px == "#":
                    img.putpixel((x0 + x, y0 + 1 + y), (255, 255, 255, 255))
        lines.append("char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15"
                     % (ord(char), x0, y0, w, H + 1, w + 1))
    # space
    lines.append("char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=4 page=0 chnl=15")
    img.save(os.path.join(out_dir, "pixel.png"))
    head = ['info face="SnesPixel" size=10 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
            'common lineHeight=11 base=8 scaleW=%d scaleH=%d pages=1 packed=0' % img.size,
            'page id=0 file="pixel.png"',
            'chars count=%d' % len(lines)]
    with open(os.path.join(out_dir, "pixel.fnt"), "w") as f:
        f.write("\n".join(head + lines) + "\n")
    print("wrote assets/fonts/pixel.fnt + pixel.png,", len(lines), "glyphs")

    # preview
    sample = "INVENTORY  Stats  Fighter 3  Coins 120\nThe quick brown fox jumps over the lazy dog! 0123456789"
    pv = Image.new("RGB", (330, 30), (29, 43, 107))
    x, y = 4, 4
    for c in sample:
        if c == "\n":
            x, y = 4, y + 12
            continue
        if c == " ":
            x += 4
            continue
        rows = G[c]
        for yy, row in enumerate(rows):
            for xx, px in enumerate(row):
                if px == "#":
                    pv.putpixel((x + xx + 1, y + yy + 2), (10, 10, 30))
                    pv.putpixel((x + xx, y + yy + 1), (255, 255, 255))
        x += len(rows[0]) + 1
    pv.resize((330 * 4, 30 * 4), Image.NEAREST).save("/tmp/font_preview.png")


if __name__ == "__main__":
    main()
